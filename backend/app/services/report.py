"""Exportable simulation reports (markdown / json)."""

from __future__ import annotations

import json
from datetime import datetime, timezone

from app.models.schema import (
    CompareResult,
    PathwayProject,
    SimulationResult,
)


def build_markdown_report(
    project: PathwayProject,
    simulation: SimulationResult | None = None,
    compare: CompareResult | None = None,
) -> str:
    lines: list[str] = []
    lines.append(f"# PathwayFlux Report — {project.meta.name}")
    lines.append("")
    lines.append(f"Generated: {datetime.now(timezone.utc).isoformat()}")
    lines.append(f"Schema version: {project.schema_version}")
    lines.append(
        f"Units: [{project.meta.units_concentration}], time [{project.meta.units_time}]"
    )
    lines.append("")
    lines.append("## Description")
    lines.append(project.meta.description or "_None_")
    lines.append("")

    lines.append("## Model composition")
    lines.append(f"- Compartments: {len(project.compartments)}")
    lines.append(f"- Metabolites: {len(project.metabolites)}")
    lines.append(f"- Enzymes: {len(project.enzymes)}")
    lines.append(f"- Cofactors: {len(project.cofactors)}")
    lines.append(f"- Inhibitors: {len(project.inhibitors)}")
    lines.append(f"- Reactions: {len(project.reactions)}")
    lines.append(f"- Scenarios: {len(project.scenarios)}")
    lines.append("")

    lines.append("## Metabolites")
    lines.append("| ID | Name | Compartment | Initial | Boundary |")
    lines.append("|---|---|---|---|---|")
    for m in project.metabolites:
        lines.append(
            f"| `{m.id}` | {m.name} | `{m.compartment_id}` | "
            f"{m.initial_concentration:g} | {m.is_boundary} |"
        )
    lines.append("")

    lines.append("## Reactions")
    for r in project.reactions:
        subs = " + ".join(
            f"{abs(s.stoichiometry):g}·{s.metabolite_id}" for s in r.substrates
        ) or "∅"
        prods = " + ".join(
            f"{abs(p.stoichiometry):g}·{p.metabolite_id}" for p in r.products
        ) or "∅"
        arrow = "⇌" if r.reversible else "→"
        lines.append(f"### {r.name} (`{r.id}`)")
        lines.append(f"- {subs} {arrow} {prods}")
        lines.append(f"- Rate law: `{r.rate_law.value}`")
        lines.append(f"- Parameters: `{r.parameters.model_dump()}`")
        if r.notes:
            lines.append(f"- Notes: {r.notes}")
        lines.append("")

    lines.append("## Assumptions")
    if project.assumptions:
        for a in project.assumptions:
            lines.append(f"- **[{a.category}]** {a.text}")
    else:
        lines.append("_None recorded._")
    lines.append("")

    if simulation and simulation.success:
        lines.append("## Simulation summary")
        lines.append(f"- Time points: {simulation.n_steps}")
        lines.append(
            f"- Interval: [{simulation.time[0]:g}, {simulation.t_end_actual:g}]"
            if simulation.time
            else "- Interval: empty"
        )
        lines.append("")
        lines.append("### Final concentrations")
        lines.append("| Metabolite | Final |")
        lines.append("|---|---|")
        for mid, series in simulation.concentrations.items():
            name = simulation.metabolite_names.get(mid, mid)
            final = series[-1] if series else float("nan")
            lines.append(f"| {name} (`{mid}`) | {final:.6g} |")
        lines.append("")
        lines.append("### Final fluxes")
        lines.append("| Reaction | Final flux |")
        lines.append("|---|---|")
        for rid, series in simulation.fluxes.items():
            name = simulation.reaction_names.get(rid, rid)
            final = series[-1] if series else float("nan")
            lines.append(f"| {name} (`{rid}`) | {final:.6g} |")
        lines.append("")

    if compare and compare.scenarios:
        lines.append("## Scenario comparison")
        for sid, res in compare.scenarios.items():
            sname = compare.scenario_names.get(sid, sid)
            lines.append(f"### {sname}")
            if not res.success:
                lines.append(f"_Failed: {res.message}_")
                continue
            for mid, series in res.concentrations.items():
                if series:
                    name = res.metabolite_names.get(mid, mid)
                    lines.append(f"- {name}: final = {series[-1]:.6g}")
            lines.append("")

    lines.append("---")
    lines.append("_Generated by PathwayFlux Forge — deterministic local ODE modeling._")
    lines.append("")
    return "\n".join(lines)


def build_json_report(
    project: PathwayProject,
    simulation: SimulationResult | None = None,
    compare: CompareResult | None = None,
) -> str:
    payload = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "project": project.model_dump(),
        "simulation": simulation.model_dump() if simulation else None,
        "compare": compare.model_dump() if compare else None,
    }
    return json.dumps(payload, indent=2)
